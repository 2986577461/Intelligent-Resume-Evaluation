_VOCATIONAL_KEYWORDS = ("职业技术", "职业学院", "高等专科", "技师学院")


def classify_school(school_name: str, degree: str) -> str:
    """
    返回 greade 字符串，例如 "c9本科"、"985硕士"、"一本本科"、"高职专科"。
    """
    name = school_name.strip()
    deg = degree.strip() if degree else ""

    if name in _C9:
        tier = "c9"
    elif name in _985:
        tier = "985"
    elif name in _211:
        tier = "211"
    elif any(kw in name for kw in _VOCATIONAL_KEYWORDS):
        tier = "高职"
    elif name.endswith("大学"):
        tier = "一本"
    elif name.endswith("学院") or name.endswith("学校"):
        tier = "二本"
    else:
        tier = "一本"  # 未知院校保守估计

    return tier + deg
